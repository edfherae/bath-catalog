SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- --------------------------------------------------------
-- База данных
-- --------------------------------------------------------

CREATE DATABASE IF NOT EXISTS `bath_projects`
    DEFAULT CHARACTER SET utf8mb4
    DEFAULT COLLATE utf8mb4_unicode_ci;

USE `bath_projects`;

-- --------------------------------------------------------
-- Таблица `project`
-- --------------------------------------------------------

DROP TABLE IF EXISTS `project`;

CREATE TABLE `project` (
    `id`          INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `title`       VARCHAR(255) NOT NULL,
    `description` TEXT NOT NULL,
    `area`        INT UNSIGNED NOT NULL COMMENT 'Площадь в кв. м',
    `floors`      TINYINT UNSIGNED NOT NULL COMMENT 'Количество этажей',
    `has_pool`    TINYINT(1) NOT NULL DEFAULT 0 COMMENT 'Наличие бассейна',
    `price`       INT UNSIGNED DEFAULT NULL COMMENT 'Цена в рублях',
    `image_url`   VARCHAR(500) NOT NULL,
    PRIMARY KEY (`id`),
    KEY `idx_area` (`area`),
    KEY `idx_floors` (`floors`),
    KEY `idx_has_pool` (`has_pool`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

